import { describe, expect, it } from 'vitest';
import { spokenDueYmd } from '../../src/llm/spoken-date.js';

/** Wednesday 2026-10-14 10:00 in Asia/Shanghai. */
const now = new Date('2026-10-14T02:00:00.000Z');
const zone = 'Asia/Shanghai';

function ymd(text: string): string | null {
  return spokenDueYmd(text, zone, now);
}

describe('spokenDueYmd', () => {
  it.each([
    ['明天上午九点提醒我打疫苗', '2026-10-15'],
    ['明儿再看', '2026-10-15'],
    ['后天打疫苗', '2026-10-16'],
    ['大后天交', '2026-10-17'],
    ['昨天的会', '2026-10-13'],
    ['前天', '2026-10-12'],
    ['大前天', '2026-10-11'],
    ['下周这天', '2026-10-21'],
    ['下星期这天', '2026-10-21'],
    ['下周同一天', '2026-10-21'],
    ['下下周这天', '2026-10-28'],
    ['上周这天', '2026-10-07'],
    ['下周一开会', '2026-10-19'],
    ['下周三', '2026-10-21'],
    ['下周日', '2026-10-25'],
    ['下周天', '2026-10-25'],
    ['这周五', '2026-10-16'],
    ['这礼拜五', '2026-10-16'],
    ['本周五', '2026-10-16'],
    ['周五', '2026-10-16'],
    ['周一', '2026-10-19'],
    ['这周一', '2026-10-12'],
    ['上周五', '2026-10-09'],
    ['周日', '2026-10-18'],
    ['周末', '2026-10-17'],
    ['这周末', '2026-10-17'],
    ['下周末', '2026-10-24'],
    ['下个周末', '2026-10-24'],
    ['下周', '2026-10-19'],
    ['下下周', '2026-10-26'],
    ['三天后', '2026-10-17'],
    ['3天以后', '2026-10-17'],
    ['过两天', '2026-10-16'],
    ['两周后', '2026-10-28'],
    ['半个月后', '2026-10-29'],
    ['两个月后', '2026-12-14'],
    ['下个月15号', '2026-11-15'],
    ['这个月20号', '2026-10-20'],
    ['月底', '2026-10-31'],
    ['下月初', '2026-11-01'],
    ['下个月', '2026-11-01'],
    ['10月20日', '2026-10-20'],
    ['十月十三日', '2027-10-13'],
    ['10月1日', '2027-10-01'],
    ['2026年10月1日', '2026-10-01'],
    ['15号开会', '2026-10-15'],
    ['10号', '2026-11-10'],
    ['后天提醒我看下周的报告', '2026-10-16'],
    ['提醒我下周三下午开会', '2026-10-21'],
  ])('%s → %s', (text, expected) => {
    expect(ymd(text)).toBe(expected);
  });

  it.each([
    '买牛奶',
    '九点开会',
    '某天再看',
    '买两天的药',
    '每天上午九点',
    '每周一上午九点',
    '每个周末',
    '每个月15号',
    '每隔两周',
    '每两天后',
    '每间隔两个月的晚上九点提醒我用油擦一下菜板',
  ])('ignores %s', (text) => {
    expect(ymd(text)).toBeNull();
  });
});
